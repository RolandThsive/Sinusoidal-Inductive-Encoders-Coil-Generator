"""
Dual_Parameters.py  -  gathers every setting of the DUAL coil generator: one stator with two coil sets (set 1
inside, set 2 outside, each with its own RX pair and its own TX ring, each read by its own IC) and one rotor
disc with two rings of metal.

You do NOT edit this file.  The settings live in nine files next to it (the Parameters folder):

    Dual_Board_Parameters.py    the one board both sets share: output, layer count, vias, clearance, bore and
                                outline, the gap between the sets, where each set's TX ends go, air gap,
                                thickness, and the rotor disc (mode, edges, the gap between the rings, arc
                                resolution, mask)
    Dual_RX1_Parameters.py      the RX coils of set 1 (inner):  loops, band, nets, profile, layers, fingers,
                                and the set's own vias and clearance (None = the board's)
    Dual_RX2_Parameters.py      the RX coils of set 2 (outer)
    Dual_TX1_Parameters.py      the TX ring of set 1:  turns, pitch, wiring, shape, tail, layers, excitation
                                frequency
    Dual_TX2_Parameters.py      the TX ring of set 2
    Dual_Rotor1_Parameters.py   ring 1 of the rotor disc (faces set 1)
    Dual_Rotor2_Parameters.py   ring 2 of the rotor disc (faces set 2)
    Dual_IC1_Parameters.py      the IC that drives set 1's TX and reads its RX: the limits the electrical
                                estimate checks set 1 against (oscillator range, tank resistance)
    Dual_IC2_Parameters.py      the IC of set 2

Every name is the Single Coil Set Generator's own, so the wiki's Parameter Reference applies to each set as it is.

The run script (Dual_Generator/Run/Dual_RunCoilGenerator.py) builds two parameter sets from these files, one per
coil set, in the Single Coil Set Generator's own names, and hands each to the Single Coil Set Generator's own builders
and checks.  The Single Coil Set Generator itself is not changed in any way.

Run, from the "Dual Coil Set Generator" folder:
    python Dual_Generator/Run/Dual_RunCoilGenerator.py
        ->  Output/DualCoil_<bore r>_<outline r>_<set 1 loops>x<set 2 loops>_<set 1 TX turns>x<set 2 TX turns>/
            Stator.kicad_pcb, Rotor.kicad_pcb (with their project files .kicad_pro), Parameters.txt
"""

